export function buildSystemPrompt(
  quality: string,
  language: string,
  preset?: string,
  customPrompt?: string
): string {
  const langInstruction =
    language && language !== "auto"
      ? `Отвечай на языке: ${language}.`
      : "Отвечай на том же языке, на котором написан исходный контент.";

  const presetAdd = preset && presetInstructions[preset] ? presetInstructions[preset] : "";
  const customAdd = customPrompt?.trim() ? `\n\nДополнительные инструкции от пользователя:\n${customPrompt.trim()}` : "";

  const qInst = qualityInstructions[quality] || qualityInstructions.balanced;
  return `Ты — эксперт по извлечению знаний. Твоя задача — проанализировать контент и создать структурированные артефакты знаний. ${qInst} ${presetAdd} ${langInstruction}${customAdd}

Ты ОБЯЗАН ответить ТОЛЬКО валидным JSON (без markdown-блоков, без лишнего текста). JSON должен иметь ТОЧНО такую структуру:
{
  "title": "Ясное, описательное название контента",
  "summary": "Резюме в Markdown внутри одной JSON-строки: ## разделы, ### подразделы, между блоками — пустая строка; списки через - или 1.; не один сплошной абзац. 200-400 слов, объективно.",
  "keyIdeas": ["Массив из 5-7 ключевых идей. Каждая должна быть практичной и применимой, с краткими примерами где уместно."],
  "flashcards": [{"question": "Чёткий конкретный вопрос", "answer": "Краткий, но полный ответ с контекстом"}],
  "structuredNotes": "Подробные заметки в формате markdown с ## заголовками, ### подзаголовками, маркированными списками и ключевыми выводами. Как заметки от умного друга.",
  "tags": ["3-5 релевантных тегов темы, в нижнем регистре"],
  "language": "определённый код языка (en, ru, es и т.д.)",
  "codeSnippets": []
}
Поле codeSnippets — массив объектов { "title", "language" (опционально), "code", "explanation" }. Пример одного элемента: {"title":"Валидация входа","language":"typescript","code":"const x = 1;","explanation":"…"}.

Требования:
- Резюме: Markdown с ## и ###, пустые строки между блоками, списки; не сплошной текст; 200-400 слов; объективно. Переносы строк внутри значения summary — только как \\n в JSON (валидная одна строка).
- Ключевые идеи: 5-7 практических, применимых инсайтов
- Карточки: минимум 5 пар Q&A для реального запоминания (не тривиальные определения)
- Заметки: хорошо структурированный markdown с примерами
- codeSnippets: если в контенте или в приложенном блоке «Кандидаты кода» есть осмысленные фрагменты — заполни массив (до 12 пунктов), иначе верни пустой массив []. Не дублируй один и тот же код. Для каждого пункта explanation обязателен.
- Всегда перефразируй текстовые поля (summary, keyIdeas, explanation), кроме поля code — там допустима точная передача кода из источника или кандидатов`;
}
